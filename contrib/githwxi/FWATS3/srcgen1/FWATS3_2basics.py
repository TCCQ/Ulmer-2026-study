########################################################################
########################################################################
#
@dataclass
class fnoptn[T](ABC):
    pass
@dataclass
class fnoptn_nil[T](fnoptn[T]):
    pass
@dataclass
class fnoptn_cons[T](fnoptn[T]):
    arg1: T
    pass
#
########################################################################
#
@dataclass
class fnlist[T](ABC):
    pass
@dataclass
class fnlist_nil[T](fnlist[T]):
    pass
@dataclass
class fnlist_cons[T](fnlist[T]):
    arg1: T
    arg2: fnlist[T]
    pass
